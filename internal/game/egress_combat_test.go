func TestToggleAutoAttack(t *testing.T) {
	r := newCombatRig(t)
	const npc = 0x0000EA07
	r.npc(1, npc, 2, 0, 0)
	r.e.TargetObjectID = npc

	// Retail (hold): a press turns it on and sends 0x000F when a swing is due.
	r.e.ToggleAutoAttack()
	got := r.take()
	if len(got) != 1 || got[0].op != protocol.OpcodeAttack || u32At(got[0].p, 0) != npc || !r.e.CombatEngaged {
		t.Fatalf("press: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}
	r.e.MaybeStopAutoAttack()
	if r.e.CombatEngaged {
		t.Error("hold mode: the release left auto-attack on")
	}
	// Not due yet: a second press sends nothing but still holds it on.
	r.e.nextSwing = r.now + 500
	r.e.ToggleAutoAttack()
	if got := r.take(); len(got) != 0 || !r.e.CombatEngaged {
		t.Errorf("press before the swing is due: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}

	// Toggle mode: a press flips it; turning it off sends nothing.
	r.e.AutoAttackToggle = true
	r.e.CombatEngaged = true
	r.e.ToggleAutoAttack()
	if got := r.take(); len(got) != 0 || r.e.CombatEngaged {
		t.Errorf("toggle off: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}
	r.e.MaybeStopAutoAttack() // no effect in toggle mode
	r.now += 1000
	r.e.ToggleAutoAttack()
	if got := r.take(); len(got) != 1 || !r.e.CombatEngaged {
		t.Errorf("toggle on: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}
	r.e.MaybeStopAutoAttack()
	if !r.e.CombatEngaged {
		t.Error("toggle mode: the release turned auto-attack off")
	}
	r.e.AutoAttackToggle = false

	// A corpse is looted (0x0015) and auto-attack stays as it was.
	r.e.CombatEngaged = false
	r.gs.Entities[npc].HPFlag = 3
	r.e.ToggleAutoAttack()
	if got := r.take(); len(got) != 1 || got[0].op != protocol.OpcodeLootCorpse || u32At(got[0].p, 0) != npc || r.e.CombatEngaged {
		t.Errorf("corpse: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}
	r.gs.Entities[npc].HPFlag = 1

	// Not attackable (0x80), or not a creature, or no target: nothing.
	r.gs.Entities[npc].NPCFlags = 0x80
	r.now += 10000
	r.e.ToggleAutoAttack()
	r.gs.Entities[npc].NPCFlags = 0
	r.slot(1, npc, entityTypePlain)
	r.e.ToggleAutoAttack()
	r.slot(1, npc, entityTypeCreature)
	r.e.TargetObjectID = 0
	r.e.ToggleAutoAttack()
	if got := r.take(); len(got) != 0 || r.e.CombatEngaged {
		t.Errorf("refused targets: sent %+v, auto-attack %v", got, r.e.CombatEngaged)
	}
}

func TestAutoAttackTick(t *testing.T) {
	r := newCombatRig(t)
	const npc = 0x00ABCDEF
	r.npc(1, npc, 3, 0, 0)
	r.e.TargetObjectID = npc
	r.gs.Player.Class, r.gs.Player.Level = 0, 50 // a warrior
	sword := ParsedItem{EquipLocation: 14, Slot: 12, AttackType: 1, Name: "sword"}
	r.gs.setLists([]ParsedItem{sword}, nil)
	var acted []int32
	r.e.setActionCB = func(id uint32, a int32) int { acted = append(acted, a); return 0 }

	// In reach (3 < 4.5): no message; the next swing waits Attack4's 6 s.
	r.e.CombatEngaged = true
	r.e.nextSwing = r.now
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 0 || r.e.nextSwing != r.now+6000 || len(acted) != 0 {
		t.Fatalf("in reach: sent %+v, next %d (now %d), actions %v", got, r.e.nextSwing, r.now, acted)
	}
	// Not due: nothing.
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 0 {
		t.Errorf("not due: sent %+v", got)
	}
	// Out of reach: my character swings the sword (25), 0x00D8, 2 s.
	r.gs.Entities[npc].X = 10
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	got := r.take()
	if len(got) != 1 || got[0].op != 0x00D8 || len(got[0].p) != 0 || r.e.nextSwing != r.now+2000 {
		t.Errorf("out of reach: sent %+v, next %d", got, r.e.nextSwing-r.now)
	}
	if len(acted) != 1 || acted[0] != 25 {
		t.Errorf("out of reach: actions %v, want the 1H slash 25", acted)
	}
	// A huge target (0x800) adds 5 to the reach: 9.5 holds 9.
	r.gs.Entities[npc].X, r.gs.Entities[npc].NPCFlags = 9, 0x800
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 0 {
		t.Errorf("huge target at 9: sent %+v", got)
	}
	// A player may not auto-attack a player.
	r.gs.Entities[npc].X, r.gs.Entities[npc].NPCFlags, r.gs.Entities[npc].NameColor = 1, 0, 2
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 1 || got[0].op != 0x00D8 {
		t.Errorf("player target: sent %+v, want 0x00D8", got)
	}
	r.gs.Entities[npc].NameColor = 0
	// A held item in slot 19: no swing, no animation, always 0x00D8.
	acted = nil
	r.gs.setLists([]ParsedItem{sword, {EquipLocation: 19, Slot: 18, Name: "torch"}}, nil)
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 1 || got[0].op != 0x00D8 || len(acted) != 0 {
		t.Errorf("held item: sent %+v, actions %v", got, acted)
	}
	// A bow (slot 18) with no arrows: "Out of arrows." and 0x00D8, no swing.
	r.gs.ChatLog = nil
	bow := ParsedItem{EquipLocation: 18, Slot: 16, AttackType: 7, Range: 30, Name: "bow"}
	r.gs.setLists([]ParsedItem{bow}, nil)
	r.gs.PlayerStats[9], r.gs.PlayerStats[10] = 100, 100
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 1 || got[0].op != 0x00D8 || len(acted) != 0 ||
		len(r.gs.ChatLog) != 1 || r.gs.ChatLog[0].Text != "Out of arrows." {
		t.Errorf("bow, no arrows: sent %+v, actions %v, chat %+v", got, acted, r.gs.ChatLog)
	}
	// With arrows (kind 1, not wearable) it reaches 30, and needs a tenth of
	// my power: "Not enough power to shoot."
	r.gs.setLists([]ParsedItem{bow, {EquipLocation: -1, Slot: -1, P18: 1, Name: "arrows"}}, nil)
	r.gs.ChatLog = nil
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 0 {
		t.Errorf("bow with arrows at 1: sent %+v", got)
	}
	r.gs.PlayerStats[9] = 9
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 1 || len(r.gs.ChatLog) != 1 || r.gs.ChatLog[0].Text != "Not enough power to shoot." {
		t.Errorf("bow, low power: sent %+v, chat %+v", got, r.gs.ChatLog)
	}
	// Off: nothing at all.
	r.e.CombatEngaged = false
	r.now = r.e.nextSwing
	r.e.autoAttackTick()
	if got := r.take(); len(got) != 0 {
		t.Errorf("auto-attack off: sent %+v", got)
	}
}

func TestSelectAndCycleTarget(t *testing.T) {
	r := newCombatRig(t)
	self := r.gs.PlayerObjectID
	r.gs.GroupActive = true
	r.gs.GroupMembers = []GroupMember{{ObjectID: self}, {ObjectID: 0x111}, {ObjectID: 0x222}, {ObjectID: 0x444}}
	r.gs.PetID = 0x333
	r.e.CombatEngaged = true

	want := func(what string, id uint32) {
		t.Helper()
		got := r.take()
		if len(got) != 1 || got[0].op != protocol.OpcodeClassicTargetInfo || len(got[0].p) != 8 ||
			u32At(got[0].p, 0) != 0 || u32At(got[0].p, 4) != id {
			t.Errorf("%s: sent %+v, want 0x0010 for %08X", what, got, id)
		}
		if r.e.target() != id || r.e.CombatEngaged || r.gs.TargetInfoValid {
			t.Errorf("%s: target %08X, auto-attack %v, info valid %v", what, r.e.target(), r.e.CombatEngaged, r.gs.TargetInfoValid)
		}
	}
	r.gs.TargetInfoValid = true
	r.e.SelectTarget(1)
	want("SelectTarget(1)", self)
	r.e.SelectTarget(2) // roster slot 0 is me: the next one
	want("SelectTarget(2)", 0x111)
	r.e.SelectTarget(3)
	want("SelectTarget(3)", 0x111)
	r.e.SelectTarget(4)
	want("SelectTarget(4)", 0x222)
	r.e.SelectTarget(5) // past the roster's size
	want("SelectTarget(5)", targetNone)
	r.e.SelectTarget(6)
	want("SelectTarget(6)", 0x333)

	// The party cycle: me, the others, the pet, wrapping.
	r.e.TargetObjectID = 0x111
	r.e.cycleDir = 1
	for _, id := range []uint32{0x222, 0x444, 0x333, self, 0x111} {
		r.e.CombatEngaged = true
		r.e.CycleTarget(true, nil)
		want("party cycle", id)
	}

	// The scene: the camera at the origin looking down +Z.
	r.gs.GroupMembers = []GroupMember{{ObjectID: self}, {ObjectID: 0x111}}
	r.npc(2, 0x111, 0, 0, 5)        // a group member: never
	r.npc(3, 0x333, 0, 0, 6)        // the pet: never
	far := r.npc(4, 0xA, 30, 0, 60) // off to the side
	near := r.npc(5, 0xB, 0, 0, 40) // straight ahead
	corpse := r.npc(6, 0xC, 0, 0, 30)
	corpse.Animation = 14    // dead: +2
	r.npc(7, 0xD, 0, 0, 250) // past 200
	ghost := r.npc(8, 0xE, 0, 0, 20)
	ghost.HPFlag = 0 // not targetable
	behind := r.npc(9, 0xF, 0, 0, -10)
	close := r.npc(10, 0x10, 0.5, 0, 1) // within sqrt(15) and ahead: 0
	r.npc(11, 0x11, 0, 0, 25).NameColor = 3
	v := &TargetView{
		Pos:     [3]float32{0, 0, 0},
		Dir:     [3]float32{0, 0, 1},
		Visible: func(x, y, z float32) bool { return z > 0 },
		ClipX:   func(x, y, z float32) float32 { return x / z },
	}
	_ = behind
	order := r.gs.SceneTargetOrder(v)
	wantOrder := []uint32{close.ObjectID, near.ObjectID, far.ObjectID, corpse.ObjectID}
	if len(order) != len(wantOrder) {
		t.Fatalf("scene order %08X, want %08X", order, wantOrder)
	}
	for i := range order {
		if order[i] != wantOrder[i] {
			t.Fatalf("scene order %08X, want %08X", order, wantOrder)
		}
	}
	// Switching lists starts at the first; then each press moves on, wrapping.
	r.e.TargetObjectID = near.ObjectID
	for _, id := range []uint32{close.ObjectID, near.ObjectID, far.ObjectID, corpse.ObjectID, close.ObjectID} {
		r.e.CycleTarget(false, v)
		want("scene cycle", id)
	}
	// An empty list (the camera far off, nothing in its frustum): no target,
	// and 0x0010 says so.
	r.e.CycleTarget(false, &TargetView{Pos: [3]float32{0, 0, 1000}, Dir: v.Dir,
		Visible: func(x, y, z float32) bool { return false }, ClipX: v.ClipX})
	want("empty scene", targetNone)

	// ClearTarget sends nothing.
	r.e.TargetObjectID = 0xB
	r.e.ClearTarget()
	if got := r.take(); len(got) != 0 || r.e.TargetObjectID != 0 {
		t.Errorf("ClearTarget: sent %+v, target %08X", got, r.e.TargetObjectID)
	}
}

func TestInteractWithTarget(t *testing.T) {
	r := newCombatRig(t)
	ent := r.npc(1, 0x777, 1, 0, 1)
	r.e.TargetObjectID = 0x777
	for _, c := range []struct {
		flags uint16
		color byte
		op    protocol.GameOpcode
	}{
		{1, 0, protocol.OpcodeMerchantDiag},
		{2, 0, protocol.OpcodeBankUI},
		{8, 0, protocol.OpcodeBlackSmithMenu},
		{3, 0, protocol.OpcodeMerchantDiag}, // merchant wins
		{0, 0, protocol.OpcodeInteract},
		{0, 2, 0}, // a player: the player menu, no message
		{0, 3, 0},
	} {
		ent.NPCFlags, ent.NameColor = c.flags, c.color
		r.e.InteractWithTarget()
		got := r.take()
		if c.op == 0 {
			if len(got) != 0 {
				t.Errorf("flags %d colour %d: sent %+v", c.flags, c.color, got)
			}
			continue
		}
		if len(got) != 1 || got[0].op != c.op || len(got[0].p) != 4 || u32At(got[0].p, 0) != 0x777 {
			t.Errorf("flags %d colour %d: sent %+v, want 0x%04X", c.flags, c.color, got, uint16(c.op))
		}
	}
	r.slot(1, 0x777, entityTypePlain) // not a creature: nothing
	r.e.InteractWithTarget()
	if got := r.take(); len(got) != 0 {
		t.Errorf("plain entity: sent %+v", got)
	}
}

