// TestSwingTablesMatchCLIENT pins getSwing, swingDelay and attackAnim to the
// golden tables generated by running CLIENT's own code (see the golden file's
// header): every class 0..15 at six levels, every combination of the seven
// equip slots. The control mutates one level band and must be caught.
func TestSwingTablesMatchCLIENT(t *testing.T) {
	check := func(fn func(cls, level int, b14, b15, b16, b18, b17, b19, b20 bool) int) int {
		bad := 0
		for cls := 0; cls < 16; cls++ {
			for li, level := range swingGoldenLevels {
				row := swingGolden[cls*len(swingGoldenLevels)+li]
				for bits := 0; bits < 128; bits++ {
					on := func(k int) bool { return bits>>k&1 != 0 }
					want := int(row[bits] - '0')
					if row[bits] >= 'a' {
						want = int(row[bits]-'a') + 10
					}
					if fn(cls, level, on(0), on(1), on(2), on(3), on(4), on(5), on(6)) != want {
						bad++
					}
				}
			}
		}
		return bad
	}
	if bad := check(getSwing); bad != 0 {
		t.Errorf("getSwing: %d of %d cases differ from CLIENT", bad, 16*len(swingGoldenLevels)*128)
	}
	mutated := func(cls, level int, b14, b15, b16, b18, b17, b19, b20 bool) int {
		if level >= 20 && level < 35 {
			level = 35
		}
		return getSwing(cls, level, b14, b15, b16, b18, b17, b19, b20)
	}
	if check(mutated) == 0 {
		t.Error("control: a getSwing with the 20-34 band dropped still matched")
	}
	for k, want := range swingDelayGolden {
		if got := swingDelay(k); got != want {
			t.Errorf("swingDelay(%d) = %d, CLIENT %d", k, got, want)
		}
	}
	for at, want := range attackAnimGolden {
		for alt := 0; alt < 2; alt++ {
			if got := attackAnim(int64(at), alt == 1); got != want[alt] {
				t.Errorf("attackAnim(%d, %v) = %d, CLIENT %d", at, alt == 1, got, want[alt])
			}
		}
	}
	// VISwing::Effect's names, through VIHashResourceID.
	for kind, want := range map[int]uint32{0: 0xDA9BEA11, 1: 0xDA9BEA11, 2: 0xDA9BEA13, 3: 0xDA9BEA13,
		4: 0xDA9BEA12, 5: 0xDA9BEA14, 6: 0xDA9BEA13, 7: 0xDA9BEA13, 8: 0x45EAC4A0, 9: 0x45EAC4A1,
		10: 0x45EAC4A2, 11: 0x45EAC4A3, 12: 0, 13: 0} {
		if got := swingEffect(kind); got != want {
			t.Errorf("swingEffect(%d) = 0x%08X, want 0x%08X", kind, got, want)
		}
	}
}

