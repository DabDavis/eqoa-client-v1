func TestFollow(t *testing.T) {
	r := newCombatRig(t)
	self := r.gs.PlayerObjectID
	r.gs.GroupActive = true
	r.gs.GroupMembers = []GroupMember{{ObjectID: self}, {ObjectID: 0x111}}
	leader := r.npc(1, 0x111, 0, 0, 10)
	r.npc(2, 0x999, 0, 0, 10)

	// Not a group member: word 1195, no following, no message.
	r.e.TargetObjectID = 0x999
	r.e.ToggleFollow()
	if r.e.Following() || len(r.take()) != 0 || len(r.gs.ChatLog) != 1 ||
		r.gs.ChatLog[0].Text != "You must target a group member to follow." {
		t.Fatalf("follow a stranger: following %v, chat %+v", r.e.Following(), r.gs.ChatLog)
	}
	r.e.TargetObjectID = 0x111
	r.e.ToggleFollow()
	if !r.e.Following() {
		t.Fatal("follow a member")
	}
	if h, move, walk := r.e.FollowStep(0); !move || walk || math.Abs(float64(h)) > 1e-6 {
		t.Errorf("at 10: heading %v move %v walk %v, want a run north", h, move, walk)
	}
	leader.Z = 5
	if _, move, walk := r.e.FollowStep(0); !move || !walk {
		t.Errorf("at 5: move %v walk %v, want a walk", move, walk)
	}
	leader.Z = 2
	if _, move, _ := r.e.FollowStep(0); move || !r.e.Following() {
		t.Errorf("at 2: move %v following %v, want a stop", move, r.e.Following())
	}
	// The stick ends it, and so does auto-attack, and so does a death.
	r.e.FollowStep(1)
	if r.e.Following() {
		t.Error("the stick did not end following")
	}
	r.e.ToggleFollow()
	r.e.CombatEngaged = true
	r.e.FollowStep(0)
	if r.e.Following() {
		t.Error("auto-attack did not end following")
	}
	r.e.CombatEngaged = false
	r.e.ToggleFollow()
	r.gs.handleCharacterDied(&protocol.Message{})
	r.e.combatTick()
	if r.e.Following() || r.e.CombatEngaged {
		t.Error("death left following or auto-attack on")
	}
	// Toggling again turns it off.
	r.e.ToggleFollow()
	r.e.ToggleFollow()
	if r.e.Following() {
		t.Error("a second /follow left it on")
	}
}

func TestFaceTargetAndStops(t *testing.T) {
	r := newCombatRig(t)
	r.npc(1, 0x555, 10, 0, 0)
	r.e.TargetObjectID = 0x555
	if _, ok := r.e.FaceTargetHeading(false); ok {
		t.Error("faced the target with auto-attack off and no swing")
	}
	r.e.CombatEngaged = true
	if h, ok := r.e.FaceTargetHeading(false); !ok || math.Abs(float64(h)-math.Pi/2) > 1e-6 {
		t.Errorf("auto-attack on: heading %v %v, want pi/2 (east)", h, ok)
	}
	// Within a second of a swing's effect it still faces; after, not.
	r.e.CombatEngaged = false
	r.e.lastSwingFX = r.now - 500
	if _, ok := r.e.FaceTargetHeading(false); !ok {
		t.Error("half a second after a swing")
	}
	if _, ok := r.e.FaceTargetHeading(true); ok {
		t.Error("half a second after a swing, with turn input")
	}
	r.e.lastSwingFX = r.now - 1000
	if _, ok := r.e.FaceTargetHeading(false); ok {
		t.Error("a second after a swing")
	}
	// The frame applies it to the player (and swings: the target is out of
	// reach at 10, so 0x00D8).
	r.e.CombatEngaged = true
	r.e.combatTick()
	if math.Abs(float64(r.gs.Player.Facing)-math.Pi/2) > 1e-6 {
		t.Errorf("combatTick left facing %v", r.gs.Player.Facing)
	}
	if got := r.take(); len(got) != 1 || got[0].op != 0x00D8 {
		t.Errorf("the frame's swing sent %+v", got)
	}
	// 0x077A stops auto-attack.
	r.gs.handleOutMatched(&protocol.Message{})
	r.e.combatTick()
	if r.e.CombatEngaged {
		t.Error("0x077A left auto-attack on")
	}
	// An assist (0x007B) targets at once without touching auto-attack.
	r.e.CombatEngaged = true
	r.gs.AssistTarget, r.gs.AssistTargetPending = 0x666, true
	r.e.combatTick()
	if got := r.take(); len(got) != 1 || got[0].op != protocol.OpcodeClassicTargetInfo || u32At(got[0].p, 4) != 0x666 ||
		r.e.TargetObjectID != 0x666 || !r.e.CombatEngaged || r.gs.AssistTargetPending {
		t.Errorf("assist: sent %+v, target %08X, auto-attack %v", got, r.e.TargetObjectID, r.e.CombatEngaged)
	}
}
