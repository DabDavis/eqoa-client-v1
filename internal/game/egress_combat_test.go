// The combat lane of the egress pass: what combat.go sends, against what a
// real PS2 sent (egress_capture_test.go) and against CLIENT's own tables.

// combatSent is one message the engine queued (through GameState.sendHook),
// with the rig's clock.
type combatSent struct {
	at uint64 // the fake clock when it went
	op protocol.GameOpcode
	p  []byte
}

// combatRig is an Engine on a GameState with no connection, whose sends are
// recorded and whose game clock the test sets.
type combatRig struct {
	e    *Engine
	gs   *GameState
	now  int64
	sent []combatSent
}

func newCombatRig(t *testing.T) *combatRig {
	t.Helper()
	r := &combatRig{now: 1000}
	r.e = NewEngine("test", 10070, 9735, 7000, "u", "p")
	r.gs = r.e.State
	r.e.clock = func() int64 { return r.now }
	r.gs.sendHook = func(op protocol.GameOpcode, p []byte) {
		r.sent = append(r.sent, combatSent{uint64(r.now), op, append([]byte(nil), p...)})
	}
	r.gs.selfKnown = true
	r.gs.PlayerObjectID = 0x1C6AFEAC
	r.gs.Player.ObjectID = r.gs.PlayerObjectID
	r.gs.Player.NameColor = 2
	r.gs.Player.HPFlag = 1
	r.gs.Player.HP = 255
	r.slot(0, r.gs.PlayerObjectID, entityTypeCreature)
	return r
}

// slot puts id on entity channel ch.
func (r *combatRig) slot(ch int, id uint32, kind byte) {
	r.gs.entitySlots[ch] = entitySlot{used: true, id: id, kind: kind}
}

// npc adds a live creature on channel ch at (x, y, z).
func (r *combatRig) npc(ch int, id uint32, x, y, z float32) *Entity {
	ent := &Entity{ObjectID: id, X: x, Y: y, Z: z, HP: 255, HPFlag: 1, Name: "npc"}
	if r.gs.Entities == nil {
		r.gs.Entities = map[uint32]*Entity{}
	}
	r.gs.Entities[id] = ent
	r.slot(ch, id, entityTypeCreature)
	return ent
}

// ops lists the opcodes sent since the last call.
func (r *combatRig) take() []combatSent {
	s := r.sent
	r.sent = nil
	return s
}

func u32At(p []byte, off int) uint32 { return binary.LittleEndian.Uint32(p[off:]) }

