// TestEgressCombatPayloads pins the PS2's combat messages: 0x0010 is two raw
// u32s (0, then the target), 0x000F one, 0x0032 the stamp, the slot byte and
// the target — and 0x000F and 0x0032 always carry the target the last 0x0010
// asked for (Send0032 and SendOp000F send m_target). The Go builders must
// make the same bytes.
func TestEgressCombatPayloads(t *testing.T) {
	r := newCombatRig(t)
	counts := map[uint16]int{}
	for _, m := range egressAll(t) {
		if m.IsState() {
			continue
		}
		p := m.Payload()
		switch m.Opcode {
		case 0x0010:
			counts[0x0010]++
			if len(p) != 8 || u32At(p, 0) != 0 {
				t.Errorf("%s: 0x0010 % X, want u32 0 + u32 target", m.Capture, p)
				continue
			}
			r.e.SendTarget(u32At(p, 4))
		case 0x000F:
			counts[0x000F]++
			if len(p) != 4 {
				t.Errorf("%s: 0x000F % X, want one u32", m.Capture, p)
				continue
			}
			r.e.SendAttack(u32At(p, 0))
		case 0x0032:
			counts[0x0032]++
			if len(p) != 9 {
				t.Errorf("%s: 0x0032 % X, want u32 + byte + u32", m.Capture, p)
				continue
			}
			r.gs.AbilityStamp = u32At(p, 0)
			r.e.SendCast(p[4], u32At(p, 5))
		default:
			continue
		}
		got := r.take()
		if len(got) != 1 || uint16(got[0].op) != m.Opcode || !bytes.Equal(got[0].p, p) {
			t.Errorf("%s: Go built %+v for the PS2's 0x%04X % X", m.Capture, got, m.Opcode, p)
		}
	}
	if counts[0x0010] < 100 || counts[0x000F] < 4 || counts[0x0032] < 8 {
		t.Fatalf("too few samples: %v", counts)
	}

	// The target the last 0x0010 named, per client.
	for _, name := range egressCaptures {
		msgs, _ := egressFromCapture(t, name)
		last := map[uint16]uint32{}
		for _, m := range msgs {
			if m.IsState() {
				continue
			}
			p := m.Payload()
			switch {
			case m.Opcode == 0x0010 && len(p) == 8:
				last[m.Client] = u32At(p, 4)
			case m.Opcode == 0x000F && len(p) == 4 && u32At(p, 0) != last[m.Client]:
				t.Errorf("%s: 0x000F at %.3f targets %08X, the last 0x0010 %08X", name, m.Time, u32At(p, 0), last[m.Client])
			case m.Opcode == 0x0032 && len(p) == 9 && u32At(p, 5) != last[m.Client]:
				t.Errorf("%s: 0x0032 at %.3f targets %08X, the last 0x0010 %08X", name, m.Time, u32At(p, 5), last[m.Client])
			}
		}
	}
}

// TestEgressAutoAttackByteIsTheButton pins 0x40 byte 36: it is m_autoAttack,
// which in the retail option set is on only while the attack button is held.
// In every capture it is 1 in short runs, never for a whole fight: at most
// 0.8 s at a time, and in ps2_main_capture nine presses over a 20-second
// fight whose server swings run on throughout.
func TestEgressAutoAttackByteIsTheButton(t *testing.T) {
	total := 0
	for _, name := range egressCaptures {
		msgs, _ := egressFromCapture(t, name)
		var start float64
		on := false
		runs := 0
		for _, m := range msgs {
			if !m.IsState() || m.Type != 0x40 || len(m.Data) < 41 {
				continue
			}
			switch {
			case m.Data[36] != 0 && !on:
				on, start = true, m.Time
				runs++
			case m.Data[36] == 0 && on:
				on = false
				if d := m.Time - start; d > 0.8 {
					t.Errorf("%s: byte 36 held for %.3f s from %.3f", name, d, start)
				}
			}
			if m.Data[36] > 1 {
				t.Errorf("%s: byte 36 = %d", name, m.Data[36])
			}
		}
		if name == "ps2_main_capture.pcap" && runs != 9 {
			t.Errorf("%s: %d byte-36 runs, want 9", name, runs)
		}
		total += runs
	}
	if total < 10 {
		t.Fatalf("only %d byte-36 runs in the captures", total)
	}
}

// presses are a capture's attack-button presses: its 0x000F (a press with
// the swing due) and the 0x40 updates where byte 36 rises with no 0x000F in
// the quarter second before (a press without), in seconds.
func capturePresses(msgs []egressMsg) (presses, attacks []float64, target uint32) {
	prev := byte(0)
	for _, m := range msgs {
		if !m.IsState() && m.Opcode == 0x000F && len(m.Payload()) == 4 {
			attacks = append(attacks, m.Time)
			presses = append(presses, m.Time)
			target = u32At(m.Payload(), 0)
			continue
		}
		if !m.IsState() || m.Type != 0x40 || len(m.Data) < 41 {
			continue
		}
		b := m.Data[36]
		if b != 0 && prev == 0 {
			fresh := true
			for _, a := range attacks {
				if m.Time-a >= 0 && m.Time-a < 0.25 {
					fresh = false
				}
			}
			if fresh {
				presses = append(presses, m.Time)
			}
		}
		prev = b
	}
	sort.Float64s(presses)
	return presses, attacks, target
}

// gearFromCapture replays a capture's server side until the MemoryDump has
// given the player's class, level and inventory.
func gearFromCapture(t *testing.T, name string) *GameState {
	t.Helper()
	d := replayReadUDP(t, filepath.Join("..", "..", "..", "pcaps", name), 10070)
	prev := log.Writer()
	log.SetOutput(io.Discard)
	defer log.SetOutput(prev)
	byEP := map[uint16]*GameState{}
	conns := map[uint16]*network.Connection{}
	for _, dg := range d {
		pkt, err := network.ParsePacket(dg, nil)
		if err != nil || pkt.Body == nil {
			continue
		}
		gs, ok := byEP[pkt.LocalEndpoint]
		if !ok {
			c, err := network.NewConnection("127.0.0.1", 9, 0xFFFE)
			if err != nil {
				t.Fatal(err)
			}
			defer c.Close()
			gs = NewGameState("test", 10070, 9735, 7000, "test")
			gs.Conn = c
			byEP[pkt.LocalEndpoint], conns[pkt.LocalEndpoint] = gs, c
		}
		for _, m := range conns[pkt.LocalEndpoint].ProcessIncoming(pkt) {
			gs.dispatchIncoming(m)
		}
		if gs.Player.Level > 0 && len(gs.ParsedItems) > 0 {
			return gs
		}
	}
	t.Skipf("%s: no MemoryDump", name)
	return nil
}

// simulateAttacks plays presses through ToggleAutoAttack, the frame's
// AutoAttackTick and the release, on the player's real gear with the target
// in reach, and returns when 0x000F went out.
func simulateAttacks(t *testing.T, gear *GameState, presses []float64, target uint32, shield bool) []float64 {
	r := newCombatRig(t)
	r.gs.Player.Class, r.gs.Player.Level = gear.Player.Class, gear.Player.Level
	inv := append([]ParsedItem(nil), gear.Inventory()...)
	if shield {
		inv = append(inv, ParsedItem{EquipLocation: 17, Slot: 13, Name: "control shield"})
	}
	r.gs.setLists(inv, nil)
	r.npc(1, target, 1, 0, 1)
	r.e.TargetObjectID = target
	var sent []float64
	for _, p := range presses {
		r.now = int64(math.Round(p * 1000))
		r.e.ToggleAutoAttack()
		r.e.autoAttackTick()
		r.e.MaybeStopAutoAttack()
		for _, m := range r.take() {
			if m.op == protocol.OpcodeAttack {
				sent = append(sent, float64(m.at)/1000)
			}
		}
	}
	return sent
}

// TestEgressAttackCadence replays each capture's presses through the ported
// auto-attack, with the swing the player's own gear makes, and expects 0x000F
// exactly where the PS2 sent it. In ps2_main_capture the level-51 bard
// dual-wields two rapiers (equip slots 14 and 15): GetSwing kind 5, "Attack4",
// a 6 s swing, so of ten presses only three find a swing due — 36.863, 44.480
// and 54.796 — and taps 3.9 and 5.6 s after the first do not. The control
// adds a shield (kind 2, 4 s) and must not reproduce it.
func TestEgressAttackCadence(t *testing.T) {
	for _, name := range []string{"ps2_main_capture.pcap", "ps2_sandstorm.pcap"} {
		t.Run(name, func(t *testing.T) {
			msgs, _ := egressFromCapture(t, name)
			presses, attacks, target := capturePresses(msgs)
			if len(attacks) == 0 {
				t.Fatalf("no 0x000F in %s", name)
			}
			gear := gearFromCapture(t, name)
			r := newCombatRig(t)
			r.gs.Player.Class, r.gs.Player.Level = gear.Player.Class, gear.Player.Level
			r.gs.setLists(append([]ParsedItem(nil), gear.Inventory()...), nil)
			kind, _, delay := r.e.Swing()
			rel := func(ts []float64) []string {
				var out []string
				for _, x := range ts {
					out = append(out, strconv.FormatFloat(x-msgs[0].Time, 'f', 3, 64))
				}
				return out
			}
			t.Logf("class %d level %d: swing kind %d, %d ms; presses at %v, the PS2's 0x000F at %v",
				gear.Player.Class, gear.Player.Level, kind, delay, rel(presses), rel(attacks))

			got := simulateAttacks(t, gear, presses, target, false)
			if !sameTimes(got, attacks) {
				t.Errorf("0x000F at %v, the PS2 sent them at %v", got, attacks)
			}
			if name == "ps2_main_capture.pcap" {
				if kind != 5 || delay != 6000 {
					t.Errorf("the bard's swing: kind %d, %d ms; want 5 (Attack4), 6000", kind, delay)
				}
				ctl := simulateAttacks(t, gear, presses, target, true)
				if sameTimes(ctl, attacks) {
					t.Errorf("control: a 4 s swing also gave %v", ctl)
				}
				t.Logf("control (a shield, 4 s): 0x000F at %v", rel(ctl))
			}
		})
	}
}

func sameTimes(a, b []float64) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if math.Abs(a[i]-b[i]) > 0.002 {
			return false
		}
	}
	return true
}

