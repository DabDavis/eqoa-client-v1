// lookupSurfaceY returns a safe travel Y for the zone containing (x,z).
// Uses midpoint of zone Y range — ground level is typically in the middle,
// with MinY being deep water/caves and MaxY being mountain peaks.
func lookupSurfaceY(x, z float32) float32 {
	for _, b := range tunariaBBoxes {
		if x >= b.MinX && x <= b.MaxX && z >= b.MinZ && z <= b.MaxZ {
			return (b.MinY + b.MaxY) / 2
		}
	}
	return 150
}
