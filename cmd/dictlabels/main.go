// dictlabels emits the client's known equipment Surface DictIDs as a JS lookup
// for the ESF texture browser (esfviewer/labels.js).
//
// The browser can read every Surface out of an ESF/CSF file, but a raw DictID
// says nothing. These are the IDs the equipment system actually binds, so the
// viewer can label the handful of surfaces that matter and let the rest be
// filtered out. Generated from the live tables rather than copied, so it cannot
// drift from what the client renders.
//
//	go run ./cmd/dictlabels > ../esfviewer/labels.js
package main

import (
	"fmt"
	"os"
	"sort"

	"github.com/eqoa/client/internal/models"
)

// label is one annotation for a DictID. Several tables can name the same ID —
// CHAR.ESF and CHARCUST.CSF share the plate DictIDs with different art — so a
// DictID maps to a list.
type label struct {
	Cat  string // filter category
	Text string // human label
}

func main() {
	out := map[int32][]label{}
	add := func(id int32, cat, text string) {
		if id == 0 {
			return
		}
		for _, l := range out[id] {
			if l.Cat == cat && l.Text == text {
				return
			}
		}
		out[id] = append(out[id], label{cat, text})
	}

	slotName := [5]string{"chest", "bracer", "gloves", "legs", "boots"}

	// Armor sets 1-8 are the PS2 $Armor rows; set 9 is the client-side ornate
	// plate, which reuses set 4's DictIDs against CHAR.ESF.
	for set := 1; set < models.ArmorSetCount; set++ {
		for slot := 0; slot < 5; slot++ {
			id := models.ArmorTextures[set][slot]
			add(id, "armor", fmt.Sprintf("%s %s", models.ArmorSetNames[set], slotName[slot]))
		}
	}

	for i := 1; i < len(models.HelmTextures); i++ {
		add(models.HelmTextures[i], "helm", fmt.Sprintf("helm %d texture", i))
	}
	for i := 1; i < len(models.HelmModelDictIDs); i++ {
		add(models.HelmModelDictIDs[i], "helmmodel", fmt.Sprintf("helm %d model", i))
	}
	for i := range models.RobeTextures {
		add(models.RobeTextures[i][0], "robe", fmt.Sprintf("robe %d chest", i))
		add(models.RobeTextures[i][1], "robe", fmt.Sprintf("robe %d legs", i))
	}
	for i, id := range models.HairTextures {
		add(id, "hair", fmt.Sprintf("hair %d", i))
	}
	add(models.HairNullTexture, "hair", "bald / null hair")

	sexName := [2]string{"m", "f"}
	for r := range models.FaceTextures {
		for i, id := range models.FaceTextures[r] {
			add(id, "face", fmt.Sprintf("%s face %d%s", models.FaceRowNames[r], i/2, sexName[i%2]))
		}
	}

	// The NPC clothing surveyed in claude-notes/npc-armor-texture-survey.md.
	for _, t := range models.NPCArmorTextures {
		text := t.Name
		if t.From != "" {
			text += " — " + t.From
		}
		add(t.DictID, "npcarmor", text)
	}

	ids := make([]int32, 0, len(out))
	for id := range out {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })

	w := os.Stdout
	fmt.Fprintln(w, "// Code generated by go-eqoa-client-v1/cmd/dictlabels. DO NOT EDIT.")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// DictID -> [{cat, text}] for surfaces the equipment system binds. A DictID")
	fmt.Fprintln(w, "// is not unique across files, so a label says what the ID means, not which")
	fmt.Fprintln(w, "// file's art you are looking at.")
	fmt.Fprintln(w, "window.ESF_LABELS = {")
	for _, id := range ids {
		// Keys are quoted: a negative numeric literal is not a legal object key,
		// and roughly half of these DictIDs are negative. Property access with a
		// number stringifies identically, so lookups are unaffected.
		fmt.Fprintf(w, "  %q: [", fmt.Sprint(id))
		for i, l := range out[id] {
			if i > 0 {
				fmt.Fprint(w, ", ")
			}
			fmt.Fprintf(w, "{c:%q,t:%q}", l.Cat, l.Text)
		}
		fmt.Fprintln(w, "],")
	}
	fmt.Fprintln(w, "};")
	fmt.Fprintf(w, "// %d labelled DictIDs\n", len(ids))
}
